package id.fhorizon.mobile.game

import android.content.Context
import org.json.JSONObject

/** One file of the supported disc's extracted folder. */
data class CatalogFile(val path: String, val size: Long, val sha256: String)

data class SupportedDump(
    val id: String,
    val serial: String,
    val region: String,
    val titleId: String,
    val sizeBytes: Long,
    val files: List<CatalogFile>,
) {
    val executable: CatalogFile? get() = files.firstOrNull { it.path.equals("default.xex", true) }
}

data class SupportedTitleUpdate(
    val id: String,
    val titleId: String,
    val mediaId: String,
    val targetVersion: String,
    val files: List<CatalogFile>,
)

/**
 * The game dumps the backend supports (assets/catalog/fh1-catalog.json,
 * generated by tools/make_catalog.py from Pinyon Shift's manifests): file
 * names, sizes and SHA-256 digests only.
 */
data class GameCatalog(val dumps: List<SupportedDump>, val titleUpdates: List<SupportedTitleUpdate>) {
    companion object {
        const val ASSET = "catalog/fh1-catalog.json"
        @Volatile private var cached: GameCatalog? = null

        fun load(context: Context): GameCatalog {
            cached?.let { return it }
            val text = context.assets.open(ASSET).bufferedReader().use { it.readText() }
            return parse(text).also { cached = it }
        }

        fun parse(text: String): GameCatalog {
            val root = JSONObject(text)
            val dumps = mutableListOf<SupportedDump>()
            val dumpArray = root.getJSONArray("dumps")
            for (i in 0 until dumpArray.length()) {
                val d = dumpArray.getJSONObject(i)
                dumps += SupportedDump(
                    id = d.getString("id"),
                    serial = d.optString("serial"),
                    region = d.optString("region"),
                    titleId = d.optString("title_id").uppercase(),
                    sizeBytes = d.optLong("size_bytes"),
                    files = parseFiles(d.getJSONArray("files")),
                )
            }
            val updates = mutableListOf<SupportedTitleUpdate>()
            val updateArray = root.optJSONArray("title_updates")
            if (updateArray != null) {
                for (i in 0 until updateArray.length()) {
                    val u = updateArray.getJSONObject(i)
                    updates += SupportedTitleUpdate(
                        id = u.getString("id"),
                        titleId = u.optString("title_id").uppercase(),
                        mediaId = u.optString("media_id").uppercase(),
                        targetVersion = u.optString("target_version"),
                        files = parseFiles(u.getJSONArray("files")),
                    )
                }
            }
            return GameCatalog(dumps, updates)
        }

        private fun parseFiles(array: org.json.JSONArray): List<CatalogFile> =
            (0 until array.length()).map { i ->
                val entry = array.getJSONArray(i)
                CatalogFile(entry.getString(0), entry.getLong(1), entry.getString(2).lowercase())
            }
    }
}
